import assert from 'node:assert/strict';
import DxfParser from 'dxf-parser';
import {loadFixtureText} from './fixture.mjs';
import {normalizeDxfEntities} from '../../frontend/src/dxf/dxfNormalizer.ts';
import {prepareGeometry} from '../../frontend/src/dxf/geometryDiagnostics.ts';
import {detectContours} from '../../frontend/src/dxf/contourEngine.ts';
import {createPartsFromContours} from '../../frontend/src/dxf/partEngine.ts';
import {createJobGeometry} from '../../frontend/src/dxf/jobGeometry.ts';
import {prepareExport,createDxfExport} from '../../frontend/src/dxf/nestingExport.ts';
import {DEFAULT_NESTING_SETTINGS} from '../../frontend/src/nesting/nestingEngine.ts';
import {runGlsNesting} from '../../frontend/src/nesting/glsNestingEngine.ts';
import {validateLayout} from '../../frontend/src/nesting/validateLayout.ts';
const parser=new DxfParser(),entities=normalizeDxfEntities(parser.parseSync(loadFixtureText())),geometry=prepareGeometry(entities,0.1);
assert.equal(geometry.issues.length,0);
const catalogue=createPartsFromContours(detectContours(geometry.curves)),job=createJobGeometry(catalogue,geometry.curves,{});
const settings={...DEFAULT_NESTING_SETTINGS,materialType:'roll',curveTolerance:0.1};
const run=await runGlsNesting(job.parts,settings,{timeBudgetMs:5000});assert.equal(run.result.placedCount,32);
const prepared=prepareExport(run.result,job.parts,job.curves,job.curvePartMap,entities,{},settings),dxf=createDxfExport(prepared.curves);
const roundtrip=prepareGeometry(normalizeDxfEntities(parser.parseSync(dxf)),0.005);
assert.equal(roundtrip.issues.filter(i=>i.blocking).length,0);
const exported=createPartsFromContours(detectContours(roundtrip.curves));assert.equal(exported.length,32);
const result={...run.result,totalCount:exported.length,placedCount:exported.length,unplacedCount:0,placements:exported.map(p=>({partId:p.id,instanceId:p.id,placed:true,x:p.bounds.minX,y:p.bounds.minY,rotation:0}))};
const validation=validateLayout(exported,{...settings,rotations:[0]},result);
console.log('PASS native spline DXF roundtrip independently checked at 0.005 mm:',JSON.stringify(validation));
